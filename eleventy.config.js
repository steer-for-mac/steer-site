/* Eleventy config. CSS, client JS and TypeScript are custom template
   extensions, which is what the docs prescribe for compiled assets; the build
   owns them, so they are watched, incremental, and never written in place. */
import Image, { eleventyImageTransformPlugin } from "@11ty/eleventy-img";
import browserslist from "browserslist";
import { build, transformSync } from "esbuild";
import { minify } from "html-minifier-next";
import { bundle, browserslistToTargets } from "lightningcss";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));

// A bug fix, not tuning. Unset, Lightning CSS rewrites every breakpoint into
// Media Queries Level 4 range syntax (`@media (width<=899px)`), which is Safari
// 16.4+, so on anything older the responsive layout silently stops applying.
// safari 15 is the floor because that is what the range syntax costs.
const TARGETS = browserslistToTargets(browserslist("safari >= 15, chrome >= 100, firefox >= 100"));

// esbuild, not tsc, for the browser: theme.ts has no imports and ships as a
// classic script, so this is a transform rather than a project build. tsc stays
// the checker (tsconfig.json is noEmit and covers the Node tools too).
const script = (code, loader) => transformSync(code, { loader, minify: true, target: "es2022" }).code;

/* iife, because the page loads the result as a classic <script defer> rather
   than a module. Throws on empty output: a silently missing home.js leaves the
   pad picker, the gallery and the launch form inert with the page still valid. */
async function bundleScript(entry) {
  const out = await build({
    entryPoints: [entry], bundle: true, write: false,
    minify: true, target: "es2022", format: "iife", logLevel: "silent",
  });
  const file = out.outputFiles[0];
  if (!file) throw new Error(`esbuild produced no output for ${entry}`);
  return file.text;
}

/* SYNCHRONOUS on purpose, so the generation happens before any template runs.
   An async filter here rendered empty inside `{% include %}` and took the rest
   of the enclosing `{% if home %}` with it -- gallery and the home.js script
   tag both gone, build exit 0, no warning. */
const SHOTS = new Map();
const SHOT_SRC = /\{\{\s*'(assets\/[^']+\.png)'\s*\|\s*shot\s*\}\}/g;
async function buildShots() {
  const tpl = readFileSync(resolve(ROOT, "src/_includes/bands/dialogs.html"), "utf8");
  for (const m of tpl.matchAll(SHOT_SRC)) {
    const src = m[1];
    if (!src || SHOTS.has(src)) continue;
    const meta = await Image(resolve(ROOT, "src", src), {
      formats: ["webp"], widths: [1440], urlPath: "/img/", outputDir: "dist/img/",
    });
    const out = meta.webp?.[0];
    if (!out) throw new Error(`no webp generated for ${src}`);
    SHOTS.set(src, out.url);
  }
}

/* Generated because @import takes no glob, so adding styles/bands/<band>.css is
   the only step. The two sheets above the bands are named rather than globbed:
   the layer each lands in is a decision, not a filename convention. */
function writeHomeEntry() {
  const bands = readdirSync(resolve(ROOT, "src/styles/bands"))
    .filter((f) => f.endsWith(".css"))
    .map((f) => f.replace(/\.css$/, ""))
    .sort();
  writeFileSync(resolve(ROOT, "src/styles/home.entry.css"),
    "/* Entry for home.css. GENERATED by eleventy.config.js: the band list comes\n" +
    "   from styles/bands/*.css, because @import takes no glob. Edit a band's own\n" +
    "   sheet, or add a new styles/bands/<band>.css and rebuild. */\n\n" +
    "@layer tokens, base, components, bands;\n\n" +
    '@import "svg-strokes.css" layer(base);\n' +
    '@import "design-system.css" layer(components);\n' +
    bands.map((b) => `@import "bands/${b}.css" layer(bands);\n`).join(""),
    "utf8");
}

/* A page's sheet is at the same path in the other tree, like a band's: swap the
   directory and the extension and vs.html gives styles/pages/vs.css.
   UNLAYERED on purpose. These replace <style> blocks that sat after the
   site.css link, which outranks every layer in it whatever the specificity;
   putting them in a layer hands those rules back to shared.css. Nothing else
   on the site is unlayered. */
const pageSheets = () => (existsSync(resolve(ROOT, "src/styles/pages"))
  ? readdirSync(resolve(ROOT, "src/styles/pages"))
    .filter((f) => f.endsWith(".css")).map((f) => f.replace(/\.css$/, "")).sort()
  : []);

/* Which sheets become files. Everything else under src/styles is reached
   through an @import and must not be emitted beside the sheet that imports it.
   Lightning CSS is a real bundler, not concatenation: it parses, so it cannot
   halve a selector list, and it understands @layer, so the cascade is declared
   in the entry files rather than implied by paste order. */
const cssPermalink = (inputPath) => {
  const p = inputPath.replace(/^\.\//, "");
  if (p.endsWith(".entry.css")) return `/${basename(p, ".entry.css")}.css`;
  if (p.includes("/styles/pages/")) return `/${basename(p)}`;
  return false;
};

/* Drop HTML comments for production.
 *
 * 17% of index.html is comments, and they are design rationale written for
 * whoever edits _includes/ next: they cite app source files, name commits, and
 * explain decisions. That is exactly the material to keep in the repo and not
 * ship to strangers. */
/* conservativeCollapse never removes whitespace, only collapses runs to one
   space: this page leans on inline-block rows where a removed space closes a
   gap the design wants. minifyJS reaches the pre-paint <head> script, the one
   file no other minifier can see because Nunjucks pastes it verbatim. */
const MINIFY = {
  removeComments: true,
  collapseWhitespace: true,
  conservativeCollapse: true,
  minifyJS: true,
  keepClosingSlash: true,
  /* Without this the minifier EXPANDS bare booleans to defer=defer and
     checked=checked -- unquoted, which html-validate rejects, and longer than
     what it replaced. */
  collapseBooleanAttributes: true,
  removeAttributeQuotes: false,
};

export default function (eleventyConfig) {
  /* Rewrites the <img> tags already in the markup, so no template changes and
     no shortcode to remember. avif and webp ahead of the original: the 29
     referenced rasters are 7.45MB of png and jpg with not one srcset.
     "auto" keeps the source width as the last candidate, and the plugin never
     upscales, so the 22px logo stays one file. */
  eleventyConfig.addPlugin(eleventyImageTransformPlugin, {
    formats: ["avif", "webp", "auto"],
    widths: [480, 960, 1440, "auto"],
    urlPath: "/img/",
    outputDir: "dist/img/",
    htmlOptions: {
      imgAttributes: { decoding: "async" },
      pictureAttributes: {},
    },
  });

  /* The gallery hydrates data-light/data-dark into src on first show, so the
     img transform never sees those paths and the seven slides -- the largest
     images on the site -- shipped as full-size png. This gives them a built
     file instead. webp, not avif: JS sets ONE src with no format negotiation,
     and avif excludes the Safari 15 this build still targets. */
  eleventyConfig.addFilter("shot", (src) => {
    const url = SHOTS.get(src);
    if (!url) throw new Error(`no built shot for ${src}; buildShots did not see it`);
    return url;
  });

  /* NO PLUGIN for the inline SVG in src/_includes/art/: eleventy-plugin-svg-
     contents was adopted first, then measured. It last published in 2022, pulls
     31 packages for cheerio, and re-serializes instead of pasting bytes, which
     rewrapped a <path> in three pad files. `{% include %}` is byte-identical.
     Nunjucks renders what it includes, so a well-formed `{{ name }}` in one of
     these files renders to empty string and deletes code silently. */

  /* src/public/ lands at the output root, so a file that has to ship under its
     own name is added by putting it there, not by editing this list. The list
     it replaces named ten files, and a root asset that was not on it -- probed
     with probe-asset.png -- was dropped without a word. */
  eleventyConfig.addPassthroughCopy("src/assets");
  eleventyConfig.addPassthroughCopy("src/screenshots");
  eleventyConfig.addPassthroughCopy({ "src/public": "/" });

  /* A template, not a copy-then-rewrite. The old build copied these out and ran
     esbuild over dist/ with --allow-overwrite, so the minifier read its own
     output directory and nothing watched the sources. */
  /* addExtension registers the compiler; this is what makes Eleventy look for
     the files at all. Without it the build writes 14 pages and no assets. */
  eleventyConfig.addTemplateFormats(["css", "js", "ts"]);
  eleventyConfig.addExtension("css", {
    outputFileExtension: "css",
    compile: (content, inputPath) => (cssPermalink(inputPath) === false ? undefined
      : async () => bundle({ filename: inputPath.replace(/^\.\//, ""), minify: true, targets: TARGETS }).code.toString()),
    compileOptions: { permalink: (content, inputPath) => () => cssPermalink(inputPath) },
  });
  /* Bundled, not transformed: home.js is an entry that imports one module per
     band from src/scripts/, so those are reached through the import graph and
     must not each emit a file of their own. iife because the page loads it as a
     classic <script defer>, not a module. */
  eleventyConfig.addExtension("js", {
    outputFileExtension: "js",
    compile: (content, inputPath) => (inputPath.includes("/scripts/") ? undefined
      : async () => bundleScript(inputPath.replace(/^\.\//, ""))),
    /* home.entry.js -> /home.js, exactly as home.entry.css -> /home.css. The
       .entry says "this imports the modules"; the output name is what the
       layout asks for. */
    compileOptions: {
      permalink: (content, inputPath) => () => `/${basename(inputPath).replace(".entry.js", ".js")}`,
    },
  });
  eleventyConfig.addExtension("ts", {
    outputFileExtension: "js",
    compile: (content) => async () => script(content, "ts"),
  });

  /* URLs on this site end in .html and always have: sitemap.xml, every internal
     link and nginx's try_files all assume it. Eleventy's default would publish
     features.html to /features/index.html and quietly break every one of them.
     Derived from the filename so a new page needs no front matter to land in
     the right place; index.src.html is the homepage's source, hence the .src. */
  eleventyConfig.addGlobalData("eleventyComputed", {
    /* Pages only. The CSS and JS extensions set their own permalink, and this
       one would rename site.entry.css to site.entry.html. */
    permalink: (data) => (data.page.inputPath.endsWith(".html")
      ? `${data.page.filePathStem.replace(/\.src$/, "")}.html` : undefined),
    /* "features", "index", ... The nav and footer compare against this rather
       than carrying a hand-set aria-current, which had drifted: 4 of 12 pages
       marked their nav link and 3 marked their footer link. */
    pageName: (data) => data.page.filePathStem.replace(/\.src$/, "").replace(/^\//, ""),
    home: (data) => data.page.filePathStem === "/index.src",
    canonical: (data) => data.page.filePathStem === "/index.src"
      ? "https://steer.seanfloyd.dev/"
      : `https://steer.seanfloyd.dev${data.page.filePathStem}.html`,
  });

  /* Footer defaults. A page overrides only what differs from every other page. */
  eleventyConfig.addGlobalData("footBottom", true);
  eleventyConfig.addGlobalData("footLegal",
    "macOS 14+ · Apple Silicon · Not affiliated with Sony, Microsoft, or Nintendo.");

  eleventyConfig.addTransform("minify-html", /** @this {{page?: {outputPath?: string}}} */ async function (content) {
    /* outputPath is `false`, not a string, for a template that opts out of
       writing -- which every @import-only sheet under src/styles does. */
    const out = this.page?.outputPath;
    if (typeof out !== "string" || !out.endsWith(".html")) return content;
    return minify(content, MINIFY);
  });

  /* The layout links <page>.css only for a page that has one, so a page with no
     sheet requests nothing. Read once at config time, like the band glob. */
  eleventyConfig.addGlobalData("pageSheets", pageSheets());

  eleventyConfig.on("eleventy.before", async () => { writeHomeEntry(); await buildShots(); });

  return {
    dir: {
      /* src/, not ".": with the repo root as input every file in it was a
         potential page, so .eleventyignore had to name the prose and
         addPassthroughCopy had to name the assets. Both were lists nobody
         updates. Eleventy requires includes and data to sit inside input. */
      input: "src",
      output: "dist",
      /* src/_includes/{bands,chrome,layouts}, mirrored by styles/{bands}. A
         band's two files are at the same path in each tree: swap
         src/_includes -> styles and .html -> .css and you have the sheet. */
      includes: "_includes",
      layouts: "_includes",
      data: "_data",
    },
    htmlTemplateEngine: "njk",
    markdownTemplateEngine: "njk",
  };
}
